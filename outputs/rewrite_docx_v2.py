def _fill_run(r_el, text):
    """清空 run 内容并按 \n 插入 <w:br/>，保留 rPr。"""
    for tag in ("w:t", "w:br", "w:tab", "w:cr"):
        for e in r_el.findall(qn(tag)):
            r_el.remove(e)
    parts = text.split("\n")
    for i, part in enumerate(parts):
        if i > 0:
            r_el.append(OxmlElement("w:br"))
        t = OxmlElement("w:t")
        t.set(qn("xml:space"), "preserve")
        t.text = part
        r_el.append(t)


def set_para_text(p_el, text):
    """把段落文本写入首个含 w:t 的 run，删除其余 run。"""
    runs = p_el.findall(qn("w:r"))
    keep = None
    for r in runs:
        if r.find(qn("w:t")) is not None:
            keep = r
            break
    if keep is None:
        if not runs:
            keep = OxmlElement("w:r")
            pPr = p_el.find(qn("w:pPr"))
            if pPr is not None:
                rPr = pPr.find(qn("w:rPr"))
                if rPr is not None:
                    keep.append(copy.deepcopy(rPr))
            p_el.append(keep)
        else:
            keep = runs[0]
    for r in runs:
        if r is not keep:
            p_el.remove(r)
    _fill_run(keep, text)


def mkpara(tpl_el, text):
    p = copy.deepcopy(tpl_el)
    set_para_text(p, text)
    return p


def insert_after(anchor_el, elements):
    cur = anchor_el
    for el in elements:
        cur.addnext(el)
        cur = el
    return cur


def set_row_texts(tr_el, texts):
    tcs = tr_el.findall(qn("w:tc"))
    for tc, text in zip(tcs, texts):
        ps = tc.findall(qn("w:p"))
        first = ps[0]
        for p in ps[1:]:
            tc.remove(p)
        set_para_text(first, text)


def fill_table(tbl, rows_data, src_row_idx=1):
    """按 rows_data 重写整张表（含表头），行数按需增减。"""
    tbl = getattr(tbl, "_tbl", tbl)
    trs = tbl.findall(qn("w:tr"))
    tpl = copy.deepcopy(trs[src_row_idx])
    while len(tbl.findall(qn("w:tr"))) < len(rows_data):
        tbl.append(copy.deepcopy(tpl))
    for tr in tbl.findall(qn("w:tr"))[len(rows_data):]:
        tbl.remove(tr)
    for tr, texts in zip(tbl.findall(qn("w:tr")), rows_data):
        set_row_texts(tr, texts)


def new_table(tpl_tbl_el, rows_data):
    """以模板表构造一张新表（首行做表头）。"""
    tbl = copy.deepcopy(tpl_tbl_el)
    trs = tbl.findall(qn("w:tr"))
    hdr = copy.deepcopy(trs[0])
    body_tpl = copy.deepcopy(trs[1]) if len(trs) > 1 else copy.deepcopy(trs[0])
    for tr in trs:
        tbl.remove(tr)
    set_row_texts(hdr, rows_data[0])
    tbl.append(hdr)
    for texts in rows_data[1:]:
        tr = copy.deepcopy(body_tpl)
        set_row_texts(tr, texts)
        tbl.append(tr)
    return tbl


def png_size(path):
    with open(path, "rb") as f:
        head = f.read(24)
    w, h = struct.unpack(">II", head[16:24])
    return w, h


def image_paragraph(img_path):
    """新建含图片的段落（返回 p 元素）。"""
    p = doc.add_paragraph()
    run = p.add_run()
    w, h = png_size(img_path)
    width = IMG_WIDTH
    height = int(width * h / w)
    if height > 8.2 * 914400:
        width = int(width * (8.2 * 914400) / height)
        height = int(8.2 * 914400)
    run.add_picture(img_path, width=width)
    return p._p


